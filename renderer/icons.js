  const levels = { '#': '', o: ' opacity=".55"', '-': ' opacity=".28"' };
  function symbol(name, source) {
    const rows = source.trim().split('\n');
    if (rows.length !== 12 || rows.some(row => row.length !== 12)) throw new Error('Иконка ' + name + ' должна быть 12 × 12');
    const paths = {};
    rows.forEach((row, y) => {
      for (let x = 0; x < 12; x++) {
        const tone = row[x];
        if (!(tone in levels)) continue;
        let end = x;
        while (end + 1 < 12 && row[end + 1] === tone) end++;
        paths[tone] = (paths[tone] || '') + 'M' + x + ' ' + y + 'h' + (end - x + 1) + 'v1h-' + (end - x + 1) + 'z';
        x = end;
      }
    });
    return '<symbol id="i-' + name + '" viewBox="0 0 12 12">' + Object.entries(paths).map(([tone, d]) => '<path d="' + d + '"' + levels[tone] + '/>').join('') + '</symbol>';
  }
  const microsoft = '<symbol id="i-microsoft" viewBox="0 0 12 12"><path fill="#f35325" d="M1 1h4v4H1z"/><path fill="#81bc06" d="M7 1h4v4H7z"/><path fill="#05a6f0" d="M1 7h4v4H1z"/><path fill="#ffba08" d="M7 7h4v4H7z"/></symbol>';
