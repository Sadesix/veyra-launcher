const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { ContentManager } = require('../main/content-manager');

function fixtures() {
  const projects = Object.fromEntries(['mainmod', 'secondmod', 'library', 'broken', 'forgeonly', 'preview', 'shader', 'pack', 'cyclea', 'cycleb', 'pinned'].map(id => [id, { id, title: id === 'mainmod' ? 'Aurora Tools' : id === 'secondmod' ? 'Waypoint Atlas' : id === 'library' ? 'Aurora Library' : id, project_type: id === 'shader' ? 'shader' : id === 'pack' ? 'resourcepack' : 'mod', icon_url: '' }]));
  const files = new Map();
  const versions = {};
  function version(id, projectId, number, dependencies = [], loaders = ['fabric'], channel = 'release') {
    const filename = projectId + '-' + number + (['shader', 'pack'].includes(projectId) ? '.zip' : '.jar');
    const url = 'https://cdn.modrinth.com/data/' + projectId + '/' + id + '/' + filename;
    const bytes = Buffer.from('fixture bytes for ' + id);
    files.set(url, bytes);
    return versions[id] = { id, project_id: projectId, version_number: number, date_published: number === '2.0' ? '2026-10-08' : '2026-10-07', version_type: channel, game_versions: ['1.21.8'], loaders, dependencies, files: [{ primary: true, filename, url, size: bytes.length, hashes: { sha512: createHash('sha512').update(bytes).digest('hex') } }] };
  }
  version('lib1', 'library', '1.0');
  version('mod1', 'mainmod', '1.0', [{ dependency_type: 'required', project_id: 'library', version_id: 'lib1' }]);
  version('mod2', 'mainmod', '2.0', [{ dependency_type: 'required', project_id: 'library', version_id: 'lib1' }]);
  version('second1', 'secondmod', '1.0', [{ dependency_type: 'required', project_id: 'library', version_id: 'lib1' }]);
  version('bad1', 'broken', '1.0');
  version('forge1', 'forgeonly', '1.0', [], ['forge']);
  version('beta1', 'preview', '1.0', [], ['fabric'], 'beta');
  version('shader1', 'shader', '1.0', [], ['iris', 'optifine']);
  version('pack1', 'pack', '1.0', [], ['minecraft']);
  version('a1', 'cyclea', '1.0', [{ dependency_type: 'required', project_id: 'cycleb' }]);
  version('b1', 'cycleb', '1.0', [{ dependency_type: 'required', project_id: 'cyclea' }]);
  version('pin1', 'pinned', '1.0', [{ dependency_type: 'required', project_id: 'mainmod', version_id: 'mod1' }]);
  let corrupt = false, corruptProject = '', delay = false;
  const requests = [];
  const fetcher = async (input, options = {}) => {
    const url = new URL(input); requests.push({ url: url.href, options }); options.signal?.throwIfAborted();
    if (url.hostname === 'cdn.modrinth.com') {
      if (delay) await new Promise((resolve, reject) => { const timer = setTimeout(resolve, 3000); options.signal?.addEventListener('abort', () => { clearTimeout(timer); reject(options.signal.reason); }, { once: true }); });
      const bytes = files.get(url.href);
      if (!bytes) return new Response('', { status: 404 });
      return new Response(corrupt || corruptProject && url.pathname.includes('/' + corruptProject + '/') ? Buffer.alloc(bytes.length, 1) : bytes);
    }
    let body;
    if (url.pathname === '/v2/tag/category') body = [{ name: 'technology', project_type: 'mod', header: 'categories' }, { name: 'realistic', project_type: 'shader' }];
    else if (url.pathname === '/v2/search') {
      const facets = url.searchParams.get('facets') || '';
      const ids = facets.includes('project_type:shader') ? ['shader'] : facets.includes('project_type:resourcepack') ? ['pack'] : ['mainmod', 'secondmod', 'broken'];
      const hits = ids.filter(id => (projects[id].title + id).toLowerCase().includes((url.searchParams.get('query') || '').toLowerCase())).map((id, i) => ({ project_id: id, title: projects[id].title, description: ['Новые инструменты и возможности для вашей игры.', 'Отмечайте находки и прокладывайте новые маршруты.', 'Тестовый проект для проверки загрузок.'][i], author: 'Veyra', downloads: 42000 - i * 10000, categories: ['technology', 'fabric'] }));
      body = { total_hits: hits.length, hits };
    }
    else if (/\/project\/[^/]+\/version$/.test(url.pathname)) body = Object.values(versions).filter(version => version.project_id === url.pathname.split('/')[3]);
    else if (/\/project\/[^/]+$/.test(url.pathname)) body = projects[url.pathname.split('/')[3]];
    else if (/\/version\/[^/]+$/.test(url.pathname)) body = versions[url.pathname.split('/')[3]];
    return new Response(JSON.stringify(body || {}), { status: body ? 200 : 404 });
  };
  return { projects, versions, files, requests, fetcher, setCorrupt: value => { corrupt = value; }, setCorruptProject: value => { corruptProject = value; }, setDelay: value => { delay = value; } };
}

async function main() {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'veyra-content-'));
  const fixture = fixtures();
  const manager = new ContentManager({ fetch: fixture.fetcher });
  const instance = { id: 'content-test', directory, minecraftVersion: '1.21.8', loader: 'fabric' };
  const run = async plan => manager.install(instance, plan.token, new AbortController().signal, () => {});
  assert.equal((await manager.list(instance, 'mods')).entries.length, 0);
  await manager.search(instance, 'mods', { query: 'aurora', category: 'technology' });
  const search = new URL(fixture.requests.at(-1).url);
  const facets = JSON.parse(search.searchParams.get('facets'));
  assert.ok(facets.some(facet => facet.includes('versions:1.21.8')) && facets.some(facet => facet.includes('categories:fabric')));
  assert.match(fixture.requests.at(-1).options.headers['User-Agent'], /VeyraLauncher/);
  assert.equal((await manager.categories('mods')).length, 1);
  assert.equal((await manager.search({ ...instance, loader: 'vanilla' }, 'mods')).hits.length, 0);
  await assert.rejects(manager.plan(instance, 'mods', 'forgeonly'), /Нет совместимой/);
  await assert.rejects(manager.plan(instance, 'mods', 'preview'), /Нет совместимой/);
  assert.equal((await manager.plan(instance, 'mods', 'preview', { preview: true })).entries.length, 1);
  const initial = await manager.plan(instance, 'mods', 'mainmod', { versionId: 'mod1' });
  assert.equal(initial.entries.length, 2);
  assert.equal(initial.entries.find(item => item.projectId === 'library').dependency, true);
  await run(initial);
  let list = await manager.list(instance, 'mods');
  assert.equal(list.entries.length, 2);
  assert.deepEqual(list.entries.find(item => item.projectId === 'library').requiredBy, ['Aurora Tools']);
  await assert.rejects(manager.toggle(instance, 'mods', 'library-1.0.jar', false), /Сначала отключите/);
  await assert.rejects(manager.trash(instance, 'mods', 'library-1.0.jar'), /Этот файл нужен/);
  await manager.toggle(instance, 'mods', 'mainmod-1.0.jar', false);
  await manager.toggle(instance, 'mods', 'library-1.0.jar', false);
  await assert.rejects(manager.toggle(instance, 'mods', 'mainmod-1.0.jar.disabled', true), /обязательные зависимости/);
  const reuse = await manager.plan(instance, 'mods', 'mainmod', { versionId: 'mod1' });
  const downloadsBefore = fixture.requests.filter(item => item.url.includes('cdn.modrinth.com')).length;
  await run(reuse);
  assert.equal(fixture.requests.filter(item => item.url.includes('cdn.modrinth.com')).length, downloadsBefore, 'Disabled existing versions must be reused and enabled');
  assert.equal((await manager.list(instance, 'mods')).counts.enabled, 2);
  const update = await manager.plan(instance, 'mods', 'mainmod');
  assert.equal(update.entries.find(item => item.projectId === 'mainmod').updating, true);
  await run(update);
  list = await manager.list(instance, 'mods');
  assert.ok(list.entries.some(item => item.version === '2.0'));
  assert.ok(!list.entries.some(item => item.name === 'mainmod-1.0.jar'));
  assert.equal(list.trash[0].name, 'mainmod-1.0.jar.disabled');
  await manager.restore(instance, list.trash[0].id);
  assert.ok((await manager.list(instance, 'mods')).entries.some(item => item.name === 'mainmod-1.0.jar.disabled'));
  const trashId = await manager.trash(instance, 'mods', 'mainmod-2.0.jar');
  await manager.restore(instance, trashId);
  assert.ok((await manager.list(instance, 'mods')).entries.some(item => item.projectId === 'mainmod'));
  fixture.setCorrupt(true);
  const bad = await manager.plan(instance, 'mods', 'broken');
  await assert.rejects(run(bad), /Контрольная сумма/);
  assert.ok(!(await manager.list(instance, 'mods')).entries.some(item => item.projectId === 'broken'));
  fixture.setCorrupt(false);
  const canceled = await manager.plan(instance, 'mods', 'broken');
  fixture.setDelay(true);
  const controller = new AbortController();
  const promise = manager.install(instance, canceled.token, controller.signal, () => {});
  setTimeout(() => controller.abort(), 50);
  await assert.rejects(promise, /abort/i);
  fixture.setDelay(false);
  assert.ok(!(await manager.list(instance, 'mods')).entries.some(item => item.projectId === 'broken'));
  assert.equal((await fs.readdir(path.join(directory, '.veyra-content-staging'))).length, 0);
  // Force manifest failure after file commit and verify that every old file is restored.
  const rollback = await manager.plan(instance, 'mods', 'broken');
  const originalSave = manager.save;
  manager.save = async () => { throw new Error('Simulated disk error'); };
  await assert.rejects(run(rollback), /disk error/);
  manager.save = originalSave;
  assert.ok(!(await manager.list(instance, 'mods')).entries.some(item => item.projectId === 'broken'));
  await manager.trash(instance, 'mods', 'mainmod-1.0.jar.disabled');
  const oldBytes = await fs.readFile(path.join(directory, 'mods', 'mainmod-2.0.jar'));
  const oldManifest = await fs.readFile(path.join(directory, '.veyra-content.json'), 'utf8');
  const rollbackUpdate = await manager.plan(instance, 'mods', 'mainmod', { versionId: 'mod1' });
  manager.save = async () => { throw new Error('Simulated update disk error'); };
  await assert.rejects(run(rollbackUpdate), /update disk error/);
  manager.save = originalSave;
  assert.deepEqual(await fs.readFile(path.join(directory, 'mods', 'mainmod-2.0.jar')), oldBytes);
  assert.equal(await fs.readFile(path.join(directory, '.veyra-content.json'), 'utf8'), oldManifest);
  assert.ok(!await fs.stat(path.join(directory, 'mods', 'mainmod-1.0.jar')).catch(() => null));
  await run(await manager.plan(instance, 'shaders', 'shader'));
  await run(await manager.plan(instance, 'resourcepacks', 'pack'));
  assert.equal((await manager.list(instance, 'shaders')).entries[0].name, 'shader-1.0.zip');
  assert.equal((await manager.list(instance, 'resourcepacks')).entries[0].name, 'pack-1.0.zip');
  const cycle = await manager.plan(instance, 'mods', 'cyclea');
  assert.equal(cycle.entries.length, 2, 'Dependency cycles must terminate');
  await run(cycle);
  await assert.rejects(manager.entry(instance, 'mods', '../outside.jar'), /Некорректное/);
  const imported = path.join(await fs.mkdtemp(path.join(os.tmpdir(), 'veyra-import-')), 'manual.jar');
  await fs.writeFile(imported, 'local file');
  await manager.import(instance, 'mods', [imported]);
  assert.ok((await manager.list(instance, 'mods')).entries.some(item => item.source === 'local' && item.name === 'manual.jar'));
  await assert.rejects(manager.import(instance, 'mods', [imported]), /Уже есть/);
  const save = path.join(path.dirname(imported), 'Adventure');
  await fs.mkdir(save); await fs.writeFile(path.join(save, 'level.dat'), 'save fixture');
  await manager.import(instance, 'saves', [save]);
  const copy = await manager.duplicateSave(instance, 'Adventure');
  await manager.renameSave(instance, copy, 'Adventure backup');
  assert.equal((await manager.list(instance, 'saves')).entries.length, 2);
  const removedSave = await manager.trash(instance, 'saves', 'Adventure');
  await manager.restore(instance, removedSave);
  assert.equal(await fs.readFile(path.join(directory, 'saves', 'Adventure', 'level.dat'), 'utf8'), 'save fixture');
  process.stdout.write('OK: compatible search, pinned/transitive/cyclic dependencies, toggles/protection/reuse, updates/recoverable originals, hashing/cancellation/rollback, shader/resource packs, local imports and save copy/rename/trash/restore.\n');
}
if (require.main === module) main().catch(error => { process.stderr.write(error.stack + '\n'); process.exitCode = 1; });
module.exports = { fixtures };
