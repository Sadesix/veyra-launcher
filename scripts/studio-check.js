const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron: electron } = require('playwright-core');

async function main() {
  const workspace = path.join(__dirname, '..');
  const data = fs.mkdtempSync(path.join(os.tmpdir(), 'veyra-studio-'));
  const directory = path.join(data, 'instances', 'aurora'); fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(data, 'settings.json'), JSON.stringify({ selectedInstanceId: 'aurora', playerName: 'LaiseyMorn', instances: [{ id: 'aurora', name: 'Aurora', loader: 'fabric', loaderVersion: '0.17.2', minecraftVersion: '1.21.8', directory }] }));
  fs.writeFileSync(path.join(data, 'version-manifest.json'), JSON.stringify({ versions: [{ id: '1.21.8', type: 'release' }] }));
  const options = { executablePath: process.argv[2] ? path.resolve(process.argv[2]) : undefined, args: process.argv[2] ? [] : ['.'], cwd: workspace, env: { ...process.env, VEYRA_TEST_DATA_DIR: data }, timeout: 120000 };
  let app = await electron.launch(options);
  const output = path.join(workspace, 'test-output'); fs.mkdirSync(output, { recursive: true });
  try {
    let page = await app.firstWindow();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.waitForFunction(() => document.getElementById('hero-name').textContent === 'Aurora');
    const original = (await page.evaluate(() => window.launcher.getState())).instances[0];
    assert.equal(original.backgroundId, 'default', 'Existing default covers must be preserved');
    await page.locator('#hero-edit').click();
    assert.equal(await page.locator('.studio-background').count(), 9);
    assert.equal(await page.locator('.studio-background.is-selected').getAttribute('data-background-id'), 'default');
    await page.locator('[data-background-id="scene-4"]').click();
    await page.locator('#edit-name').fill('Aurora · Северное сияние');
    await page.locator('#edit-note').fill('Всё началось с одного блока.\nДальше — целое приключение.');
    await page.locator('[data-accent="blue"]').click();
    assert.equal(await page.locator('#instance-dialog-title').textContent(), 'Aurora · Северное сияние');
    await page.locator('.studio-fields').evaluate(node => { node.scrollTop = 0; });
    await page.waitForTimeout(750);
    await page.screenshot({ path: path.join(output, 'build-studio.png') });
    await page.locator('[data-studio-tab="game"]').click();
    await page.locator('#edit-memory-default').uncheck();
    await page.locator('#edit-memory').fill('3');
    assert.equal(await page.locator('#studio-memory-preview').textContent(), '3 ГБ памяти');
    await page.locator('#instance-form button[type="submit"]').click();
    await page.waitForFunction(() => !document.getElementById('instance-dialog').open);
    let item = (await page.evaluate(() => window.launcher.getState())).instances[0];
    assert.equal(item.backgroundId, 'scene-4'); assert.equal(item.memoryGb, 3); assert.equal(item.accent, 'blue');
    await app.evaluate(({ app, dialog }, cover) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cover] }); }, path.join(workspace, 'assets', 'backgrounds', 'scene-8.webp'));
    await page.locator('#hero-edit').click(); await page.locator('#edit-cover').click();
    await page.waitForFunction(() => document.getElementById('studio-cover-name').textContent === 'Своя обложка');
    await page.locator('#instance-form button[type="submit"]').click();
    await page.waitForFunction(() => !document.getElementById('instance-dialog').open);
    item = (await page.evaluate(() => window.launcher.getState())).instances[0]; assert.equal(item.coverFile, 'cover.webp');
    await page.locator('#hero-edit').click();
    assert.equal(await page.locator('.studio-background.is-selected').count(), 0);
    await page.locator('#random-cover').click();
    const candidate = await page.locator('.studio-background.is-selected').getAttribute('data-background-id');
    assert.notEqual(candidate, 'scene-4'); assert.notEqual(candidate, 'default');
    await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.getElementById('instance-dialog').open);
    item = (await page.evaluate(() => window.launcher.getState())).instances[0]; assert.equal(item.coverFile, 'cover.webp', 'Cancelled preset selection must preserve custom cover');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(980, 650));
    await page.locator('#hero-edit').click(); await page.waitForTimeout(750);
    const box = await page.locator('#instance-dialog').boundingBox(); const size = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }));
    assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= size.width + 1 && box.y + box.height <= size.height + 1);
    assert.equal(await page.locator('#instance-dialog').evaluate(node => node.scrollWidth <= node.clientWidth), true);
    await page.screenshot({ path: path.join(output, 'build-studio-small.png') });
    await page.locator('[data-background-id="scene-2"]').click();
    await page.locator('#instance-form button[type="submit"]').click(); await page.waitForFunction(() => !document.getElementById('instance-dialog').open);
    item = (await page.evaluate(() => window.launcher.getState())).instances[0]; assert.equal(item.coverFile, ''); assert.equal(item.backgroundId, 'scene-2');
    const created = await page.evaluate(() => window.launcher.createInstance({ name: 'New build', minecraftVersion: '1.21.8', loader: 'vanilla' }));
    assert.match(created.backgroundId, /^scene-[1-8]$/);
    assert.ok(!created.directory.includes('portable-extraction'));
    assert.deepEqual(errors, []);
    await app.close(); app = await electron.launch(options); page = await app.firstWindow();
    await page.waitForFunction(() => document.getElementById('hero-name').textContent === 'New build');
    const restarted = await page.evaluate(() => window.launcher.getState());
    assert.equal(restarted.instances.find(entry => entry.id === created.id).backgroundId, created.backgroundId);
    assert.equal(restarted.instances.find(entry => entry.id === 'aurora').backgroundId, 'scene-2');
    process.stdout.write('OK: studio/gallery/live preview, custom covers preserved, cancelled random preview, saved presets, minimum window, per-build settings and persistent random backgrounds for new builds.\n');
  } finally { await app.close(); }
}
main().catch(error => { process.stderr.write(error.stack + '\n'); process.exitCode = 1; });
