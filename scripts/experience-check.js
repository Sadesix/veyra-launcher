const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron: electron } = require('playwright-core');

async function main() {
  const dataDirectory = fs.mkdtempSync(path.join(os.tmpdir(), 'veyra-experience-'));
  const output = path.join(__dirname, '..', 'test-output');
  fs.mkdirSync(output, { recursive: true });
  const fixtures = ['aurora', 'atlas'].map((id, i) => ({ id, name: i ? 'Atlas' : 'Aurora', minecraftVersion: '1.21.8', loader: i ? 'fabric' : 'vanilla', directory: path.join(dataDirectory, 'instances', id), playedMs: i ? 10800000 : 5460000 }));
  fixtures.forEach(item => fs.mkdirSync(item.directory, { recursive: true }));
  fs.writeFileSync(path.join(dataDirectory, 'settings.json'), JSON.stringify({ playerName: 'LaiseyMorn', selectedInstanceId: 'aurora', instances: fixtures }));
  fs.writeFileSync(path.join(dataDirectory, 'version-manifest.json'), JSON.stringify({ versions: [{ id: '1.21.8', type: 'release' }, { id: '25w01a', type: 'snapshot' }] }));
  const options = { executablePath: process.argv[2] ? path.resolve(process.argv[2]) : undefined, args: process.argv[2] ? [] : ['.'], cwd: path.join(__dirname, '..'), env: { ...process.env, VEYRA_TEST_DATA_DIR: dataDirectory }, timeout: 120000 };
  let app = await electron.launch(options);
  try {
    let page = await app.firstWindow();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.waitForFunction(() => document.getElementById('hero-name').textContent === 'Aurora');
    assert.equal(await page.locator('#greeting-name').textContent(), 'LaiseyMorn');
    assert.match(await page.locator('#greeting-time').textContent(), /Доброе утро|Добрый день|Добрый вечер|Доброй ночи/);
    assert.equal(await page.locator('#capsule-playtime').textContent(), '1 ч 31 мин');
    assert.equal(await page.locator('body').evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(8, 9, 17)');
    for (const selector of ['.wordmark', '.page-heading', '#hero-name', '#home-count']) assert.equal(await page.locator(selector).first().evaluate(node => getComputedStyle(node).userSelect), 'none');
    assert.equal(await page.locator('#search-input').evaluate(node => getComputedStyle(node).userSelect), 'text');
    assert.equal(await page.locator('#logs-content').evaluate(node => getComputedStyle(node).userSelect), 'text');
    assert.doesNotMatch(await page.locator('body').innerText(), /экземпляр|Microsoft/i);
    await page.evaluate(() => { window.__originalCard = document.querySelector('#home-instance-grid [data-instance-id="aurora"]'); });
    for (const id of ['atlas', 'aurora', 'atlas']) await page.locator('#home-instance-grid [data-instance-id="' + id + '"]').click();
    await page.waitForFunction(() => document.getElementById('hero-name').textContent === 'Atlas');
    assert.ok(await page.evaluate(() => window.__originalCard === document.querySelector('#home-instance-grid [data-instance-id="aurora"]')), 'Selecting must preserve card DOM and its animations');
    assert.equal(await page.locator('#capsule-playtime').textContent(), '3 ч 0 мин');
    await page.waitForTimeout(800);
    assert.equal(await page.locator('.hero-outgoing').count(), 0);
    await page.locator('#home-instance-grid [data-instance-id="atlas"]').click({ button: 'right' });
    assert.equal(await page.locator('#build-context-menu [role="menuitem"]').count(), 8);
    await page.keyboard.press('End');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.action), 'trash');
    await page.keyboard.press('Escape');
    assert.ok(await page.locator('#build-context-menu').isHidden());
    await page.locator('#hero-card').click({ button: 'right', position: { x: 30, y: 25 } });
    await page.locator('#build-context-menu [data-action="star"]').click();
    assert.equal((await page.evaluate(() => window.launcher.getState())).instances.find(item => item.id === 'atlas').favorite, true);
    await page.locator('#hero-card').click({ button: 'right', position: { x: 30, y: 25 } });
    await page.locator('#build-context-menu [data-action="edit"]').click();
    await page.locator('#hero-rename-input').fill('Atlas Prime');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.getElementById('hero-name').textContent === 'Atlas Prime');
    await page.locator('#create-top').click();
    await page.waitForTimeout(750);
    const box = await page.locator('#create-dialog').boundingBox();
    assert.ok(box.x > 200, 'Creation panel must enter from the right');
    await page.screenshot({ path: path.join(output, 'creation-sheet.png') });
    await page.mouse.click(110, 400);
    await page.waitForFunction(() => !document.getElementById('create-dialog').open);
    await page.locator('#create-top').click();
    await page.locator('#version-search').fill('1.21.8');
    await page.locator('[data-version="1.21.8"]').click();
    assert.equal(await page.locator('#chosen-version').textContent(), '1.21.8');
    await page.locator('[data-version-kind="snapshot"]').click();
    await page.waitForFunction(() => [...document.querySelectorAll('.version-tile')].some(button => button.textContent.includes('Snapshot')));
    assert.ok((await page.evaluate(() => window.launcher.getState())).settings.showSnapshots);
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => !document.getElementById('create-dialog').open);
    await page.locator('.rail-button[data-view="settings"]').click();
    await page.locator('[data-atmosphere="crystal"]').click();
    assert.equal(await page.locator('#appearance-transparency-value').textContent(), '40%');
    assert.equal((await page.evaluate(() => window.launcher.getState())).settings.appearance.transparency, 0, 'Preview must not save');
    await page.locator('.rail-button[data-view="home"]').click();
    assert.equal(await page.locator('body').evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(8, 9, 17)', 'Discard unsaved preview on leaving settings');
    await page.locator('.rail-button[data-view="settings"]').click();
    await page.locator('[data-atmosphere="mist"]').click();
    await page.locator('#save-settings').click();
    assert.deepEqual((await page.evaluate(() => window.launcher.getState())).settings.appearance, { transparency: 18, brightness: 80, blur: 28, picture: true });
    await assert.rejects(() => page.evaluate(() => window.launcher.saveSettings({ appearance: { transparency: 99 } })));
    await page.locator('.atmosphere-settings').scrollIntoViewIfNeeded();
    await page.waitForTimeout(500);
    await page.screenshot({ path: path.join(output, 'atmosphere.png') });
    await page.locator('.rail-button[data-view="home"]').click();
    assert.equal(await page.locator('.content').evaluate(node => node.scrollTop), 0);
    await page.locator('#toast').waitFor({ state: 'hidden' });
    await page.screenshot({ path: path.join(output, 'home-experience.png') });
    assert.deepEqual(errors, []);
    await app.close();
    app = await electron.launch(options);
    page = await app.firstWindow();
    await page.locator('#hero-name').waitFor();
    const restored = await page.evaluate(() => window.launcher.getState());
    assert.equal(restored.instances.find(item => item.id === 'atlas').name, 'Atlas Prime');
    assert.equal(restored.instances.find(item => item.id === 'aurora').playedMs, 5460000);
    assert.deepEqual(restored.settings.appearance, { transparency: 18, brightness: 80, blur: 28, picture: true });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('#create-top').click();
    assert.equal(await page.locator('#create-dialog').evaluate(node => getComputedStyle(node).animationDuration), '1e-05s');
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => !document.getElementById('create-dialog').open);
    process.stdout.write('OK: greeting, playtime, stable cards, transitions, context menu, creation sheet, version search/Snapshots, appearance preview/persistence and reduced motion.\n');
  } finally { await app.close(); }
}
main().catch(error => { process.stderr.write(error.stack + '\n'); process.exitCode = 1; });
