const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron: electron } = require('playwright-core');

async function main() {
  const workspace = path.join(__dirname, '..');
  const data = fs.mkdtempSync(path.join(os.tmpdir(), 'veyra-content-ui-'));
  const game = path.join(data, 'instances', 'aurora');
  const output = path.join(workspace, 'test-output');
  fs.mkdirSync(output, { recursive: true });
  for (const folder of ['mods', 'saves/Adventure', 'resourcepacks', 'shaderpacks']) fs.mkdirSync(path.join(game, folder), { recursive: true });
  fs.writeFileSync(path.join(game, 'mods', 'manual.jar'), 'manual mod fixture');
  fs.writeFileSync(path.join(game, 'saves', 'Adventure', 'level.dat'), 'save fixture');
  fs.writeFileSync(path.join(game, 'resourcepacks', 'manual-pack.zip'), 'pack fixture');
  fs.writeFileSync(path.join(game, 'shaderpacks', 'manual-shader.zip'), 'shader fixture');
  const importFile = path.join(data, 'new-local.jar'); fs.writeFileSync(importFile, 'new import fixture');
  fs.writeFileSync(path.join(data, 'settings.json'), JSON.stringify({ selectedInstanceId: 'aurora', instances: [{ id: 'aurora', name: 'Aurora', minecraftVersion: '1.21.8', loader: 'fabric', loaderVersion: '0.17.2', directory: game }] }));
  const options = { executablePath: process.argv[2] ? path.resolve(process.argv[2]) : undefined, args: process.argv[2] ? [] : ['.'], cwd: workspace, env: { ...process.env, VEYRA_TEST_DATA_DIR: data }, timeout: 120000 };
  let app = await electron.launch(options);
  try {
    let page = await app.firstWindow();
    const errors = []; page.on('pageerror', failure => errors.push(failure.message));
    await page.locator('#hero-content').waitFor();
    await app.evaluate(({ app, dialog }, setup) => {
      const nodeRequire = process.getBuiltinModule('module').createRequire(app.getAppPath() + '/package.json');
      const mock = nodeRequire(setup.fixtures).fixtures();
      const original = globalThis.fetch;
      globalThis.fetch = (url, options) => /https:\/\/(api|cdn)\.modrinth\.com\//.test(String(url)) ? mock.fetcher(url, options) : original(url, options);
      globalThis.__contentMock = mock;
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [setup.importFile] });
    }, { fixtures: path.join(workspace, 'scripts', 'content-check.js'), importFile });
    await page.locator('#hero-content').click();
    await page.locator('[data-content-name="manual.jar"]').waitFor();
    assert.equal(await page.locator('.scroll-roller').count(), 0);
    assert.match(await page.locator('#content-build-meta').textContent(), /Aurora.*1\.21\.8.*Fabric/);
    await page.locator('[data-content-name="manual.jar"] [role="switch"]').click();
    await page.locator('[data-content-name="manual.jar.disabled"]').waitFor();
    assert.ok(fs.existsSync(path.join(game, 'mods', 'manual.jar.disabled')));
    await page.locator('#content-local-filter').selectOption('disabled');
    assert.equal(await page.locator('.content-row').count(), 1);
    await page.locator('#content-local-filter').selectOption('all');
    await page.locator('#content-import').click();
    await page.locator('[data-content-name="new-local.jar"]').waitFor();
    assert.equal(await page.locator('.content-row').count(), 2);
    await page.locator('#content-catalog-mode').click();
    await page.locator('[data-project-id="mainmod"]').waitFor();
    await page.locator('#content-category').selectOption('technology');
    await page.locator('[data-project-id="mainmod"]').waitFor();
    await page.waitForTimeout(500);
    await page.screenshot({ path: path.join(output, 'content-catalog.png') });
    await page.locator('[data-project-id="mainmod"] button').click();
    await page.waitForFunction(() => document.querySelectorAll('.plan-entry').length === 2);
    assert.match(await page.locator('#content-plan-entries').textContent(), /Aurora Library.*Зависимость/s);
    assert.equal(await page.locator('#content-version').inputValue(), 'mod2');
    await page.waitForTimeout(500);
    await page.screenshot({ path: path.join(output, 'content-dependencies.png') });
    await page.locator('#content-plan-install').click();
    await page.locator('[data-content-name="mainmod-2.0.jar"]').waitFor();
    await page.locator('[data-content-name="library-1.0.jar"]').waitFor();
    assert.ok(fs.existsSync(path.join(game, 'mods', 'library-1.0.jar')));
    assert.equal(await page.locator('.content-row').count(), 4);
    await page.locator('[data-content-name="library-1.0.jar"] [role="switch"]').click();
    await page.waitForFunction(() => document.getElementById('content-error').textContent.includes('Сначала отключите'));
    assert.ok(fs.existsSync(path.join(game, 'mods', 'library-1.0.jar')));
    await page.locator('#content-search').fill('Aurora');
    assert.equal(await page.locator('.content-row').count(), 2);
    await page.locator('#content-search').fill('');
    await page.waitForTimeout(500);
    await page.screenshot({ path: path.join(output, 'content-installed.png') });
    await page.locator('[data-content-name="mainmod-2.0.jar"] button[title="Переместить в корзину"]').click();
    await page.locator('[data-content-name="mainmod-2.0.jar"]').waitFor({ state: 'hidden' });
    await page.locator('#content-local-filter').selectOption('trash');
    await page.locator('[data-content-name="mainmod-2.0.jar"] button').click();
    await page.waitForFunction(() => document.getElementById('content-results').textContent.includes('Корзина пуста'));
    await page.locator('[data-content-kind="saves"]').click();
    await page.locator('#content-local-filter').selectOption('all');
    await page.locator('[data-content-name="Adventure"]').waitFor();
    assert.equal(await page.locator('#content-catalog-mode').isHidden(), true);
    await page.locator('[data-content-name="Adventure"] button[title="Сделать копию сохранения"]').click();
    await page.locator('[data-content-name="Adventure — копия 1"]').waitFor();
    await page.locator('[data-content-name="Adventure — копия 1"] button[title="Переименовать папку"]').click();
    await page.locator('#save-rename-input').fill('Adventure Backup');
    await page.locator('#save-rename-input').press('Enter');
    await page.locator('[data-content-name="Adventure Backup"]').waitFor();
    assert.equal(fs.readFileSync(path.join(game, 'saves', 'Adventure Backup', 'level.dat'), 'utf8'), 'save fixture');
    await page.locator('[data-content-kind="shaders"]').click();
    await page.locator('[data-content-name="manual-shader.zip"]').waitFor();
    await page.locator('[data-content-kind="resourcepacks"]').click();
    await page.locator('[data-content-name="manual-pack.zip"]').waitFor();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(980, 650));
    await page.waitForTimeout(700);
    assert.equal(await page.locator('#content-dialog').evaluate(node => node.scrollWidth > node.clientWidth + 1), false, 'Content workspace must fit the minimum window');
    assert.equal(await page.locator('.content-body').evaluate(node => node.scrollWidth > node.clientWidth + 1), false);
    await page.screenshot({ path: path.join(output, 'content-small.png') });
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => !document.getElementById('content-dialog').open);
    assert.deepEqual(errors, []);
    await app.close();
    app = await electron.launch(options); page = await app.firstWindow();
    await page.locator('#hero-content').click();
    await page.locator('[data-content-name="mainmod-2.0.jar"]').waitFor();
    assert.equal((await page.evaluate(() => window.launcher.getContent('aurora', 'mods'))).entries.find(item => item.projectId === 'library').dependency, true);
    process.stdout.write('OK: actual content IPC, manual import/toggle, compatible catalog/categories, dependency preview/install/protection, local search/filter, trash/restore, save copy/rename, all four sections, minimum size and persistence. Downloads use Modrinth fixture responses.\n');
  } finally { await app.close().catch(() => {}); }
}
main().catch(error => { process.stderr.write(error.stack + '\n'); process.exitCode = 1; });
