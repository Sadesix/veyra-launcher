const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { ContentManager } = require('../main/content-manager');
const { CartStore } = require('../main/cart-store');
const { buildName } = require('../main/build-name');
const { fixtures } = require('./content-check');
async function main() {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'veyra-cart-'));
  const store = new CartStore(path.join(directory, 'content-carts.json'));
  const picks = [{ kind: 'mods', projectId: 'mainmod', versionId: 'mod2', title: 'Aurora Tools' }, { kind: 'mods', projectId: 'secondmod', versionId: 'second1', title: 'Waypoint Atlas' }];
  await Promise.all([store.set('aurora', picks), store.set('atlas', [picks[1]])]);
  assert.equal((await new CartStore(store.file).get('aurora')).length, 2);
  assert.equal((await store.get('atlas')).length, 1);
  await assert.rejects(async () => store.set('aurora', [picks[0], picks[0]]), /Некорректный проект/);
  const fixture = fixtures(); const manager = new ContentManager({ fetch: fixture.fetcher });
  const instance = { id: 'aurora', directory: path.join(directory, 'game'), minecraftVersion: '1.21.8', loader: 'fabric' };
  const plan = await manager.planBatch(instance, await store.get('aurora'));
  assert.equal(plan.entries.length, 3); assert.equal(plan.entries.filter(item => item.dependency).length, 1);
  assert.equal(plan.entries.filter(item => item.projectId === 'library').length, 1);
  assert.equal((await manager.list(instance, 'mods')).entries.length, 0, 'Planning never installs files');
  await assert.rejects(manager.planBatch(instance, [{ kind: 'mods', projectId: 'pinned', versionId: 'pin1' }, picks[0]]), /другую версию/);
  await assert.rejects(manager.planBatch(instance, [picks[0], { kind: 'mods', projectId: 'pinned', versionId: 'pin1' }]), /другую версию/);
  fixture.setCorruptProject('broken');
  const broken = await manager.planBatch(instance, [...picks, { kind: 'mods', projectId: 'broken', versionId: 'bad1' }]);
  await assert.rejects(manager.install(instance, broken.token, new AbortController().signal, () => {}), /Контрольная сумма/);
  assert.equal((await manager.list(instance, 'mods')).entries.length, 0); assert.equal((await store.get('aurora')).length, 2);
  fixture.setCorruptProject('');
  const result = await manager.install(instance, plan.token, new AbortController().signal, () => {});
  assert.equal(result.added, 3); assert.equal((await manager.list(instance, 'mods')).entries.length, 3);
  const mixed = await manager.planBatch(instance, [{ kind: 'shaders', projectId: 'shader', versionId: 'shader1' }, { kind: 'resourcepacks', projectId: 'pack', versionId: 'pack1' }]);
  await manager.install(instance, mixed.token, new AbortController().signal, () => {});
  assert.equal((await manager.list(instance, 'shaders')).entries.length, 1); assert.equal((await manager.list(instance, 'resourcepacks')).entries.length, 1);
  const used = [{ id: '1', name: 'Сборка' }, { id: '2', name: 'Сборка 2' }];
  assert.equal(buildName('', []), 'Сборка'); assert.equal(buildName('  ', used), 'Сборка 3'); assert.equal(buildName('', used, '1'), 'Сборка');
  assert.equal(buildName(' Aurora ', used), 'Aurora'); assert.throws(() => buildName('X', used), /Название/);
  await fs.writeFile(store.file, '{malformed'); await assert.rejects(store.set('aurora', []), /оставлен для восстановления/); assert.equal(await fs.readFile(store.file, 'utf8'), '{malformed');
  process.stdout.write('OK: durable per-build carts, serialized writes, shared dependencies once, batch conflicts in both orders, failure before commit, mixed content, automatic names and preserving damaged cart files.\n');
}
main().catch(error => { process.stderr.write(error.stack + '\n'); process.exitCode = 1; });
